def _is_uri_path(obj: object) -> bool:
    """Return True when `obj` is already a `URIPath` instance."""
    return isinstance(obj, URIPath)


def _iter_files(path: PathLike, *, suffix: Optional[str] = None):
    """Iterate over files below `path`, honoring both local and URI paths."""
    if isinstance(path, URIPath):
        iterator = path.iterdir(files_only=True)
    else:
        iterator = (child for child in path.iterdir() if child.is_file())
    for child in iterator:
        if suffix is None or child.suffix == suffix:
            yield child


def _write_geojson_bytes(
    out_path: PathLike, payload: bytes, atomic: bool = True
) -> None:
    """Write GeoJSON bytes, optionally via atomic rename for local paths."""
    parent = out_path.parent
    parent.mkdir(parents=True, exist_ok=True)

    if isinstance(out_path, URIPath):
        # Remote paths rely on URIPath to sync caches back to the backend.
        with out_path.open("wb") as f:
            f.write(payload)
        return

    if atomic:
        tmp = out_path.with_suffix(out_path.suffix + ".PART")
        with open(tmp, "wb", buffering=1 << 20) as f:
            f.write(payload)
        tmp.replace(out_path)
    else:
        with open(out_path, "wb", buffering=1 << 20) as f:
            f.write(payload)


def _worker(
    csv,
    overlap,
    results_dir,
    output_dir,
    prefix,
    object_type,
    set_classification,
    annotation_shape,
    label_col,
    usecols,
    dtype,
    atomic_writes,
):
    """Process a single CSV in a worker process and persist the GeoJSON."""
    # Build + encode (serial)
    out_path, geojson = _build_geojson_dict_from_csv(
        csv,
        overlap=overlap,
        results_dir=results_dir,
        output_dir=output_dir,
        prefix=prefix,
        object_type=object_type,
        set_classification=set_classification,
        annotation_shape=annotation_shape,
        label_col=label_col,
        usecols=usecols,
        dtype=dtype,
    )

    payload = _dumps(geojson)

    # Write (atomic)
    _write_geojson_bytes(out_path, payload, atomic=atomic_writes)


def write_geojsons(
    csvs: List[PathLike],
    *,
    results_dir: PathLike,
    overlap: float,
    # input_dir: Path = Path("."),
    output_dir: Path = Path("."),
    prefix: str = "prob",
    num_workers=8,
    object_type: str = "tile",
    set_classification: bool = False,
    annotation_shape: str = "bbox",  # "bbox" or "polygon"
    label_col: Optional[str] = None,
    atomic_writes: bool = True,
    overwrite: bool = False,
    usecols: Optional[
        List[str]
    ] = None,  # e.g., ["minx","miny","width","height", "polygon_wkt", *prob_cols]
    dtype: Optional[Dict] = None,  # e.g., {"minx":"int32", ...}
    show_progress: bool = True,
    print_timings: bool = False,
) -> None:
    """Convert CSV outputs to GeoJSON concurrently and store results."""
    # Basic validations
    if not results_dir.exists():
        raise FileNotFoundError(f"results_dir does not exist: {results_dir}")

    missing_dirs = sorted(
        {p.parent for p in csvs if not p.parent.exists()}, key=lambda x: str(x)
    )
    if missing_dirs:
        missing_str = ", ".join(str(d) for d in missing_dirs)
        raise FileNotFoundError(
            "GeoJSON input CSV directory not found: " f"{missing_str}"
        )

    out_root = results_dir / output_dir
    out_root.mkdir(parents=True, exist_ok=True)

    # Skip those already done (unless overwrite requested)
    if overwrite:
        already = set()
    else:
        already = {p.stem for p in _iter_files(out_root, suffix=".geojson")}
    csvs = [p for p in csvs if p.stem not in already]
    total = len(csvs)
    if total == 0:
        if print_timings:
            print("No new CSVs to process.")
        return

    pbar = (
        tqdm(total=total, desc="Files completed", dynamic_ncols=True)
        if show_progress
        else None
    )

    # Run with progress bar
    with ProcessPoolExecutor(max_workers=num_workers) as ex:
        futures = [
            ex.submit(
                _worker,
                args,
                overlap,
                results_dir,
                output_dir,
                prefix,
                object_type,
                set_classification,
                annotation_shape,
                label_col,
                usecols,
                dtype,
                atomic_writes,
            )
            for args in csvs
        ]

        # pbar = tqdm(total=len(futures)) if pbar is None else pbar
        for f in cancellable_as_completed(futures, ex):
            # throttle_when_busy(target_util=0.9)
            f.result()
            if pbar:
                pbar.update(1)

    if pbar:
        pbar.close()
