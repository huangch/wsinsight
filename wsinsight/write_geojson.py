def _dumps(obj) -> bytes:
    """Serialize a GeoJSON payload; already-encoded bytes pass straight through."""
    if isinstance(obj, (bytes, bytearray)):
        return bytes(obj)
    return orjson.dumps(obj, option=orjson.OPT_SERIALIZE_NUMPY)


# --------------------------
# Helpers
# --------------------------
def _make_distinct_colors(
    n: int,
    s: float = 0.70,
    v: float = 0.90,
    shuffle: bool = True,
    seed: Optional[int] = None,
):
    """Return `n` well-spaced HSV-derived colors for class visualization."""
    if n <= 0:
        raise ValueError("n must be > 0")
    hues = [i / n for i in range(n)]
    if shuffle and n > 2:
        order, L, R = [], 0, n - 1
        while L <= R:
            order.append(L)
            if L != R:
                order.append(R)
            L += 1
            R -= 1
        hues = [hues[i] for i in order]
    if seed is not None:
        import random

        random.seed(seed)

    out = []
    for h in hues:
        r, g, b = hsv_to_rgb(h, s, v)
        R, G, B = (int(round(r * 255)), int(round(g * 255)), int(round(b * 255)))
        out.append(
            {"hex": f"#{R:02X}{G:02X}{B:02X}", "rgb": (R, G, B), "hsv": (h, s, v)}
        )
    return out


# --------------------------
# BOX path (vectorized)
# --------------------------
def _dataframe_to_geojson_box_fast(
    df: pd.DataFrame,
    prob_cols: List[str],
    overlap: float,
    *,
    prefix: str = "prob",
    object_type: str = "tile",
    set_classification: bool = False,
    color_list: Optional[List[dict]] = None,
    class_names: Optional[List[str]] = None,
) -> dict:
    """Vectorize CSV tile boxes into a GeoJSON FeatureCollection."""
    # Keep only valid rows for probs
    df = df.dropna(subset=[c for c in prob_cols if c.startswith(prefix)])

    # Pull numeric columns to arrays (no per-row pandas calls)
    xywh = df[["minx", "miny", "width", "height"]].to_numpy(dtype=np.int64, copy=False)
    minx, miny, w, h = xywh.T

    # Vectorized patch math
    pw = np.rint(w * (1.0 - overlap)).astype(np.int64)
    ph = np.rint(h * (1.0 - overlap)).astype(np.int64)
    pmx = np.rint((w - pw) * 0.5).astype(np.int64)
    pmy = np.rint((h - ph) * 0.5).astype(np.int64)

    minx2 = minx + pmx
    miny2 = miny + pmy
    maxx2 = minx2 + pw
    maxy2 = miny2 + ph

    # Closed ring coordinates (N, 5, 2)
    coords = np.stack(
        [
            np.stack([maxx2, miny2], axis=1),
            np.stack([maxx2, maxy2], axis=1),
            np.stack([minx2, maxy2], axis=1),
            np.stack([minx2, miny2], axis=1),
            np.stack([maxx2, miny2], axis=1),
        ],
        axis=1,
    )

    # Probs as matrix, argmax vectorized (classification only)
    probs = df[prob_cols].to_numpy(dtype=np.float32, copy=False)
    arg = probs.argmax(axis=1)

    if color_list is None:
        color_list = _make_distinct_colors(len(prob_cols))

    if class_names is None:
        class_names = [
            f"{prefix}_{c[len(prefix) + 1:]}"
            if c.startswith(f"{prefix}_")
            else f"{prefix}_{c}"
            for c in prob_cols
        ]

    # All numeric non-geometry columns → measurements (includes prob_*, hplot_*, ncomp_*, etc.)
    # Exclude internal __oh_*__ one-hot columns generated by the label_col path.
    measure_cols = [
        c
        for c in df.columns
        if c not in _GEOM_COLS
        and not c.startswith("__oh_")
        and pd.api.types.is_numeric_dtype(df[c])
    ]
    meas_arr = df[measure_cols].to_numpy(dtype=np.float64, copy=False)

    # Build features in one tight Python loop (no pandas ops inside)
    features = []
    for i in range(len(df)):
        measurements = {
            c: (None if np.isnan(v) else float(v))
            for c, v in zip(measure_cols, meas_arr[i], strict=False)
        }
        feat = {
            "type": "Feature",
            "id": str(uuid.uuid4()),
            # "geometry": {"type": "Polygon", "coordinates": [list(map(tuple, coords[i]))]},
            "geometry": {"type": "Polygon", "coordinates": [coords[i].tolist()]},
            "properties": {
                "isLocked": True,
                "measurements": measurements,
                "objectType": object_type,
            },
        }
        if set_classification:
            ci = int(arg[i])
            feat["properties"]["classification"] = {
                "name": class_names[ci],
                "color": list(color_list[ci]["rgb"]),
            }
        features.append(feat)

    return {"type": "FeatureCollection", "features": features}


# --------------------------
# POLYGON/WKT path (GeoPandas + Shapely vectorized)
# --------------------------
def _sanitize_polygon_rings(
    df: pd.DataFrame,
    geom: np.ndarray,
) -> Tuple[np.ndarray, int, int]:
    """Repair rings so every feature is a strictly valid polygon.

    JTS-based GeoJSON consumers (e.g. QuPath) run
    ``GeometryPrecisionReducer`` on import, which raises
    ``IllegalArgumentException: Reduction failed, possible invalid input``
    for self-touching rings -- cv2.findContours emits these for cells with
    a 1-pixel neck, where the contour revisits a vertex ("pinch" contour).
    GEOS' ``make_valid`` repairs such geometry and is a semantic no-op on
    already-valid rings.

    Rows that still do not resolve to a polygon -- a null WKT (degenerate
    single-pixel cell with no stored contour) or a contour that collapses
    to zero area -- fall back to their bbox rectangle
    (``minx``/``miny``/``width``/``height``) so no cell is dropped.

    Returns ``(geometries, n_repaired, n_boxed)``.  When nothing is
    invalid the original ``geom`` array is returned unmodified.
    """
    # is_valid() -> False for null AND for self-touching rings
    bad = np.flatnonzero(~shapely.is_valid(geom))
    if bad.size == 0:
        return geom, 0, 0

    wkb = shapely.to_wkb(geom)  # nulls -> b""; only the bad rows are touched
    fixed_wkb = wkb.copy()
    have_bbox = all(c in df.columns for c in ("minx", "miny", "width", "height"))
    minx = miny = w = h = None
    if have_bbox:
        minx, miny, w, h = (
            df[["minx", "miny", "width", "height"]]
            .to_numpy(dtype=np.float64, copy=False)
            .T
        )
    n_repaired = 0
    n_boxed = 0
    for i in bad:
        g = shapely.from_wkb(wkb[i])
        replacement = None
        if g is not None:
            try:
                fixed = shapely.make_valid(g)
            except Exception:
                fixed = None
            if fixed is not None and not fixed.is_empty:
                if fixed.geom_type in ("MultiPolygon", "GeometryCollection"):
                    k = int(shapely.get_num_geometries(fixed))
                    parts = [shapely.get_geometry(fixed, j) for j in range(k)]
                else:
                    parts = [fixed]
                polys = [
                    p
                    for p in parts
                    if p is not None and p.geom_type == "Polygon" and not p.is_empty
                ]
                # keep the dominant lobe; a pinch splits the cell at the neck
                if polys:
                    replacement = max(polys, key=lambda p: p.area)
        if replacement is None:
            if not have_bbox:
                continue  # legacy behaviour: leave the geometry null
            if not all(np.isfinite(v) for v in (minx[i], miny[i], w[i], h[i])):
                continue
            bw = max(float(w[i]), 1.0)
            bh = max(float(h[i]), 1.0)
            replacement = shapely.box(minx[i], miny[i], minx[i] + bw, miny[i] + bh)
            n_boxed += 1
        else:
            n_repaired += 1
        fixed_wkb[i] = shapely.to_wkb(replacement)
    return shapely.from_wkb(fixed_wkb), n_repaired, n_boxed


def _dataframe_to_geojson_polygon_fast(
    df: pd.DataFrame,
    prob_cols: List[str],
    *,
    prefix: str = "prob",
    object_type: str = "tile",
    set_classification: bool = False,
    color_list: Optional[List[dict]] = None,
    class_names: Optional[List[str]] = None,
    crs: Optional[str] = None,
) -> dict:
    """Convert WKT-backed polygon annotations into a GeoJSON dict."""
    geom = from_wkt(df["polygon_wkt"])
    return orjson.loads(
        _polygon_geojson_bytes(
            df.drop(columns=["polygon_wkt"]),
            geom,
            prob_cols,
            prefix=prefix,
            object_type=object_type,
            set_classification=set_classification,
            color_list=color_list,
            class_names=class_names,
        )
    )


def _polygon_geojson_bytes(
    props: pd.DataFrame,
    geom: np.ndarray,
    prob_cols: List[str],
    *,
    prefix: str = "prob",
    object_type: str = "tile",
    set_classification: bool = False,
    color_list: Optional[List[dict]] = None,
    class_names: Optional[List[str]] = None,
) -> bytes:
    """Serialize polygons plus per-cell properties straight to GeoJSON bytes.

    The FeatureCollection is never materialised as a Python dict.
    ``shapely.to_geojson`` is a ufunc, so contour vertices stay inside GEOS
    instead of becoming nested lists -- that round-trip is what made
    ``GeoDataFrame.to_json`` dominate the export.
    """
    # Repair self-touching rings (JTS importers, e.g. QuPath, crash on them)
    # and demote null/degenerate rows to their bbox rectangle.
    geom, n_repaired, n_boxed = _sanitize_polygon_rings(props, geom)
    if n_repaired or n_boxed:
        logger.info(
            "annotation_shape='polygon': repaired %d self-touching ring(s) "
            "and wrote %d degenerate cell(s) as bbox rectangle(s).",
            n_repaired,
            n_boxed,
        )

    probs = props[prob_cols].to_numpy(dtype=np.float32, copy=False)
    idx = probs.argmax(axis=1)

    if class_names is None:
        class_names = [
            f"{prefix}_{c[len(prefix) + 1:]}"
            if c.startswith(f"{prefix}_")
            else f"{prefix}_{c}"
            for c in prob_cols
        ]
    if color_list is None:
        color_list = _make_distinct_colors(len(prob_cols))

    # All numeric non-geometry columns -> measurements (includes prob_*,
    # hplot_*, ncomp_*, ...).  Exclude internal __oh_*__ one-hot columns.
    measure_cols = [
        c
        for c in props.columns
        if c not in _GEOM_COLS
        and not c.startswith("__oh_")
        and pd.api.types.is_numeric_dtype(props[c])
    ]
    meas_arr = props[measure_cols].to_numpy(dtype=np.float64, copy=False)

    # Plain arrays so the per-row record build never re-enters pandas.
    col_names = [c for c in props.columns if not c.startswith("__oh_")]
    col_arrays = [props[c].to_numpy() for c in col_names]

    geom_json = shapely.to_geojson(geom)

    opt = orjson.OPT_SERIALIZE_NUMPY
    parts: List[bytes] = [b'{"type":"FeatureCollection","features":[']
    sep = b""
    for i in range(len(props)):
        record = {c: a[i] for c, a in zip(col_names, col_arrays, strict=False)}
        record["objectType"] = object_type
        if set_classification:
            ci = int(idx[i])
            record["classification"] = {
                "name": class_names[ci],
                "color": list(color_list[ci]["rgb"]),
            }
        record["measurements"] = {
            c: (None if np.isnan(v) else float(v))
            for c, v in zip(measure_cols, meas_arr[i], strict=False)
        }
        record["isLocked"] = True

        gj = geom_json[i]
        parts.append(sep)
        parts.append(b'{"type":"Feature","geometry":')
        parts.append(b"null" if gj is None else gj.encode())
        parts.append(b',"properties":')
        parts.append(orjson.dumps(record, option=opt))
        parts.append(b"}")
        sep = b","
    parts.append(b"]}")
    return b"".join(parts)


